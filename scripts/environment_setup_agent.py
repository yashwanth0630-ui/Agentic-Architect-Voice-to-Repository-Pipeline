    def create_setup_plan(
        self,
        prompt: str,
        tech_stack: Optional[str] = None,
        project_name: Optional[str] = None,
        explicit_project_id: Optional[str] = None,
        env: Optional[HostEnvironment] = None
    ) -> SetupPlan:
        """
        Builds a safe, deterministic setup plan with explicit argument arrays.
        Requires user approval prior to execution.
        """
        if env is None:
            env = environment_detector.get_host_environment()

        stack = tech_stack or "python"
        slug = explicit_project_id or sanitize_project_id(project_name or prompt)
        display_title = (project_name or slug.replace("-", " ")).title()

        # Allocate workspace directory through ProjectManager
        meta = self.pm.create_project(
            name_or_prompt=display_title,
            project_type=stack,
            description=prompt,
            explicit_id=slug
        )
        workspace = meta.workspace_path
        project_id = meta.project_id

        operations: List[SetupOperation] = []
        host_python = env.python.executable_path or sys.executable
        host_npm = env.npm.executable_path or ("npm.cmd" if os.name == "nt" else "npm")

        # 1. Scaffolding operation
        operations.append(SetupOperation(
            op_id="op_1_scaffold",
            op_type="SCAFFOLD_FILES",
            title="Generate Scaffolding",
            description=f"Write initial {stack} project structure and configuration files",
            command_args=[],
            affects_paths=["."],
            estimated_duration_sec=1
        ))

        if stack in ("python", "fastapi"):
            # 2. Virtual environment creation
            venv_path = os.path.join(workspace, ".venv")
            operations.append(SetupOperation(
                op_id="op_2_create_venv",
                op_type="CREATE_VENV",
                title="Create Python Virtual Environment",
                description="Initialize project-isolated .venv runtime environment",
                command_args=[host_python, "-m", "venv", "--system-site-packages", ".venv"],
                affects_paths=[".venv"],
                estimated_duration_sec=3
            ))

            # 3. Pip install
            venv_python = self.get_venv_python_path(workspace)
            operations.append(SetupOperation(
                op_id="op_3_pip_install",
                op_type="PIP_INSTALL",
                title="Install Python Dependencies",
                description="Install dependencies from requirements.txt into .venv",
                command_args=[venv_python, "-m", "pip", "install", "-r", "requirements.txt"],
                affects_paths=[".venv", "requirements.txt"],
                estimated_duration_sec=8
            ))

            # 4. Validation
            operations.append(SetupOperation(
                op_id="op_4_validate",
                op_type="VALIDATE",
                title="Validate Application Syntax",
                description="Verify Python AST and module imports compile cleanly",
                command_args=[venv_python, "-m", "py_compile", "main.py"],
                affects_paths=["main.py"],
                estimated_duration_sec=2
            ))

            # 5. Start server
            if stack == "fastapi":
                operations.append(SetupOperation(
                    op_id="op_5_start_server",
                    op_type="START_DEV_SERVER",
                    title="Start FastAPI Uvicorn Server",
                    description="Launch development server on 0.0.0.0 and verify HTTP health endpoint",
                    command_args=[venv_python, "-m", "uvicorn", "main:app", "--host", "0.0.0.0"],
                    affects_paths=["main.py"],
                    estimated_duration_sec=4
                ))

        elif stack == "react":
            # 2. NPM install
            operations.append(SetupOperation(
                op_id="op_2_npm_install",
                op_type="NPM_INSTALL",
                title="Install NPM Dependencies",
                description="Hydrate React and Vite packages into project node_modules",
                command_args=[host_npm, "install"],
                affects_paths=["node_modules", "package-lock.json"],
                estimated_duration_sec=12
            ))

            # 3. Start server
            operations.append(SetupOperation(
                op_id="op_3_start_server",
                op_type="START_DEV_SERVER",
                title="Start Vite Dev Server",
                description="Launch Vite server binding to 0.0.0.0 for LAN preview",
                command_args=[host_npm, "run", "dev", "--", "--host", "0.0.0.0"],
                affects_paths=["package.json"],
                estimated_duration_sec=5
            ))

        elif stack == "fullstack":
            b_venv_python = self.get_venv_python_path(os.path.join(workspace, "backend"))
            # 2. Backend venv
            operations.append(SetupOperation(
                op_id="op_2_create_backend_venv",
                op_type="CREATE_VENV",
                title="Create Backend Virtual Environment",
                description="Initialize .venv inside backend/ directory",
                command_args=[host_python, "-m", "venv", "--system-site-packages", ".venv"],
                cwd_rel="backend",
                affects_paths=["backend/.venv"],
                estimated_duration_sec=3
            ))

            # 3. Backend pip install
            operations.append(SetupOperation(
                op_id="op_3_backend_pip_install",
                op_type="PIP_INSTALL",
                title="Install Backend Dependencies",
                description="Install FastAPI & Uvicorn into backend/.venv",
                command_args=[b_venv_python, "-m", "pip", "install", "-r", "requirements.txt"],
                cwd_rel="backend",
                affects_paths=["backend/.venv", "backend/requirements.txt"],
                estimated_duration_sec=8
            ))

            # 4. Frontend npm install
            operations.append(SetupOperation(
                op_id="op_4_frontend_npm_install",
                op_type="NPM_INSTALL",
                title="Install Frontend Dependencies",
                description="Install React packages in frontend/ directory",
                command_args=[host_npm, "install"],
                cwd_rel="frontend",
                affects_paths=["frontend/node_modules"],
                estimated_duration_sec=12
            ))

            # 5. Start fullstack server
            operations.append(SetupOperation(
                op_id="op_5_start_fullstack_servers",
                op_type="START_DEV_SERVER",
                title="Start Full-Stack Coordinated Servers",
                description="Launch FastAPI backend API and React Vite frontend dev servers",
                command_args=[],
                affects_paths=["backend", "frontend"],
                estimated_duration_sec=6
            ))

        elif stack == "static_web":
            # Start static preview server
            operations.append(SetupOperation(
                op_id="op_2_start_static_server",
                op_type="START_DEV_SERVER",
                title="Start Static HTTP Server",
                description="Serve HTML/CSS/JS via local LAN preview server",
                command_args=[],
                affects_paths=["index.html"],
                estimated_duration_sec=2
            ))

        from datetime import datetime, timezone
        now_iso = datetime.now(timezone.utc).isoformat()
        plan_id = f"plan-{project_id}"

        summary_text = (
            f"Set up an isolated {stack.upper()} development environment for '{display_title}'. "
            f"Includes {len(operations)} operations: generating template files, configuring dependencies, "
            f"and launching a local development server for live preview on your phone."
        )

        plan = SetupPlan(
            plan_id=plan_id,
            project_id=project_id,
            project_name=display_title,
            tech_stack=stack,
            workspace_path=workspace,
            summary=summary_text,
            operations=operations,
            requires_approval=True,
            approved=False,
            status="planned",
            created_at=now_iso,
            updated_at=now_iso
        )

        return plan


