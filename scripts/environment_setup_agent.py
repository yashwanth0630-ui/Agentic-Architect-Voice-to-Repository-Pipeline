@dataclass
class SetupOperation:
    op_id: str
    op_type: str  # "SCAFFOLD_FILES", "CREATE_VENV", "PIP_INSTALL", "NPM_INSTALL", "VALIDATE", "START_DEV_SERVER"
    title: str
    description: str
    command_args: List[str] = field(default_factory=list)
    cwd_rel: str = "."
    affects_paths: List[str] = field(default_factory=list)
    estimated_duration_sec: int = 5
    status: str = "pending"  # "pending", "in_progress", "completed", "failed", "skipped", "cancelled"
    error: Optional[str] = None
    output_log: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "SetupOperation":
        return cls(**data)


@dataclass
class SetupPlan:
    plan_id: str
    project_id: str
    project_name: str
    tech_stack: str  # "python", "fastapi", "react", "fullstack", "static_web"
    workspace_path: str
    summary: str
    operations: List[SetupOperation]
    requires_approval: bool = True
    approved: bool = False
    status: str = "planned"  # "planned", "approved", "in_progress", "completed", "failed", "cancelled"
    error: Optional[str] = None
    preview_url: Optional[str] = None
    preview_port: Optional[int] = None
    created_at: str = ""
    updated_at: str = ""

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d["operations"] = [op.to_dict() for op in self.operations]
        return d

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "SetupPlan":
        ops = [SetupOperation.from_dict(o) for o in data.get("operations", [])]
        data_copy = dict(data)
        data_copy["operations"] = ops
        return cls(**data_copy)


